/// Equity module configuration.
///
/// By default this module exposes **generic CRUD** over the four entities via
/// [`EquityModule::all_crud_routes`] — an unguarded surface for trusted/admin/seeding contexts.
///
/// The validated, event-sourced cap-table write surface (`EquityWriteService`) and the read contract
/// (`EquityQueryService`) are **un-composed**: no in-workspace service drives them yet. They are gated
/// behind the `unstable-write-service` feature and are not part of the committed contract.
///
/// Use the builder pattern to configure and register this module:
///
/// ```text
/// let equity = EquityModule::builder()
///     .with_database(pool.clone())
///     .build()?;
///
/// // Unguarded full CRUD (trusted/admin); compose a guarded router for production.
/// let router = equity.all_crud_routes();
/// ```
pub struct EquityModule {
    pub dividend_service: Arc<DividendService>,
    pub share_class_service: Arc<ShareClassService>,
    pub shareholder_service: Arc<ShareholderService>,
    pub share_transaction_service: Arc<ShareTransactionService>,
}

impl EquityModule {
    /// Create a new module builder
    pub fn builder() -> EquityModuleBuilder {
        EquityModuleBuilder::new()
    }

    /// Mount ALL generated CRUD endpoints (12 per entity) with NO domain
    /// validation — the fully **unguarded** surface. A well-formed request can
    /// create invalid rows or soft-delete a referenced master out from under its
    /// dependents. Prefer a guarded composition (read + validated writes) for any
    /// real deployment; use this only in trusted/admin/seeding contexts.
    pub fn all_crud_routes(&self) -> Router {
        use presentation::http::{
            create_dividend_routes,
            create_share_class_routes,
            create_shareholder_routes,
            create_share_transaction_routes,
        };

        Router::new()
            .merge(create_dividend_routes(self.dividend_service.clone()))
            .merge(create_share_class_routes(self.share_class_service.clone()))
            .merge(create_shareholder_routes(self.shareholder_service.clone()))
            .merge(create_share_transaction_routes(self.share_transaction_service.clone()))
    }

}

