//! Equity Module — cap table + equity accounting (shareholders, share classes, share transactions,
//! dividends).
//!
//! ## What this crate ships by default
//!
//! Generic CRUD over the four entities, mounted via [`EquityModule::all_crud_routes`]. That surface is
//! **unguarded**: a well-formed request can write a row the domain would forbid (e.g. soft-delete a
//! `Shareholder` a transaction still references, or insert a register movement that drives a holding
//! negative). It is intended for trusted/admin/seeding contexts only — compose a guarded router for any
//! real deployment.
//!
//! ## What is NOT yet a committed contract
//!
//! The hand-authored cap-table write surface (`EquityWriteService`: issue / transfer / buyback /
//! dividend, with its GL port and lifecycle events) and the read contract (`EquityQueryService`) are
//! **un-composed** — no in-workspace service constructs the write service, injects its sinks, implements
//! the query trait, or mounts the guarded router. They are gated behind the `unstable-write-service`
//! Cargo feature and exist for tests + a future composing service, not for dependents today.
//!
